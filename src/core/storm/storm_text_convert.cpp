// 1.13c Storm+0x356A0: UTF-8 scan -> UTF-16 unit count. Retail indexes its class table (0x6FC35590) with a SIGNED
// char: bytes 0x00-0x7F read zeros (k = 0) and bytes 0x80-0xFF read the 128 bytes before the table (0x6FC35510),
// which are other data, not a UTF-8 length rule. kLeadHigh is that window as it reads at Storm's preferred base
// (its first 8 bytes are relocated pointers). Every byte is also accumulated signed (movsbl).
static const uint8_t kLeadHigh[128] = {
    168, 104, 195, 111, 160, 104, 195, 111,  63, 119, 100, 115, 116,  97,  98,  99,
     48,  49,   0,   0, 139,   0, 137,   0, 199,   0,  35,   0,  33,   0, 129,   4,
     11,   0,   9,   0, 129,   1,  51,   0,  49,   0, 129,   6,   3,   0,   1,   0,
    129,   0,  43,   0,  41,   0, 129,   5, 247,   2, 247,   2, 247,   2, 193,   1,
    193,   1, 193,   1,   4,   0,   7,   6,   5,   1,   2,   3,   0,   0,   0,   0,
      0,   0,   0,   4,   0,   0,   0,   0,   0,   0,   1,   5,   2,   6,   3,   7,
      0,   0,   0,   0,   0,   0,   0,   0, 128,  48,   0,   0, 128,  32,  14,   0,
    128,  32, 200,   3, 128,  32,   8, 250, 128,  32,   8, 130,   0,   0,   0,   0};
int32_t Storm_Utf8CountUnits(const uint8_t* s, uint32_t limit, uint32_t* out) {
    static const uint32_t base[6] = {0, 0x3080, 0xE2080, 0x3C82080, 0xFA082080u, 0x82082080u};
    if (!limit || !s) { if (out) *out = 0; return -1; }
    // limit 0x7FFFFFFF means "end = 0xFFFFFFFF"; no real buffer reaches it, so treat it as unbounded.
    const uint64_t end = limit == 0x7FFFFFFFu ? UINT64_MAX : limit;
    uint64_t i = 0;
    uint32_t units = 0;
    for (;;) {
        if (end <= i) { if (out) *out = (uint32_t)i; return -1; }
        const uint8_t c = s[i];
        const uint32_t k = c < 0x80 ? 0 : kLeadHigh[c - 0x80];
        if (end <= i + k) { if (out) *out = (uint32_t)i; return (int32_t)(-1 - (int32_t)k); }
        if (k > 5) {
            // Retail's switch has no case: nothing is accumulated, the pointer stays put, and v = 0 - base[k] with
            // base[k] read past the 6-entry table. That word is 0 for these k, so v == 0 ends the scan here.
            if (k == 6 || k == 7 || k == 8 || k == 9 || k == 11 || k == 14 || k == 32 || k == 33 || k == 35 ||
                k == 41 || k == 43 || k == 48 || k == 49 || k == 51) {
                if (out) *out = (uint32_t)i;
                return (int32_t)(units + 1);
            }
            __builtin_trap();  // nonzero base[k]: retail re-reads the same byte forever
        }
        uint32_t v = 0;
        for (uint32_t j = 0; j <= k; ++j) v = (v << 6) + (uint32_t)(int32_t)(int8_t)s[i + j];
        i += k + 1;
        v -= base[k];
        if (v < 0x10000) { ++units; if (v == 0) { if (out) *out = (uint32_t)i; return (int32_t)units; } }
        else if (v < 0x110000) units += 2;
        else ++units;
    }
}

// 1.13c Storm+0x35990: UTF-16 scan -> UTF-8 byte count incl. NUL.
int32_t Storm_Utf16CountUtf8Bytes(const uint16_t* s, uint32_t limit, uint32_t* out) {
    if (!s || !limit) { if (out) *out = 0; return -1; }
    uint32_t i = 0, bytes = 0;
    while (i < limit) {
        uint32_t u = s[i];
        if (u == 0) { ++bytes; ++i; if (out) *out = i; return (int32_t)bytes; }
        uint32_t cp = u, step = 1;
        if (u >= 0xD800 && u <= 0xDBFF) {
            if (i + 1 >= limit) { if (out) *out = i + 1; return -1; }
            uint32_t lo = s[i + 1];
            if (lo >= 0xDC00 && lo <= 0xDFFF) { cp = 0x10000 + ((u - 0xD800) << 10) + (lo - 0xDC00); step = 2; }
        }
        bytes += cp < 0x80 ? 1 : cp < 0x800 ? 2 : cp < 0x10000 ? 3 : 4;
        i += step;
    }
    if (out) *out = i;
    return -1;
}

// Shared loop of 0x35A90 / 0x35AF0: cap 0 writes nothing; each source byte is looked up in the word table while cap
// remains; the terminator is stored only when the source ended with room left. The NUL test precedes every lookup,
// so table entry 0 is never read. Returns units written.
static uint32_t byteToWideCopy(uint16_t* dst, const uint8_t* src, uint32_t cap, const uint16_t* table) {
    uint32_t n = 0, i = 0;
    if (cap) {
        while (src[i] && n < cap) dst[n++] = table[src[i++]];
        if (!src[i] && n < cap) dst[n++] = 0;
    }
    return n;
}

