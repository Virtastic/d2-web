// Compress a payload with an arbitrary built table (per-symbol length + canonical code).  Emits
// `lengths[symbol]` bits of `codes[symbol]` MSB-first; returns the byte count (no frame header) or -1.
int huffmanCompressWith(const uint8_t* lengths, const uint8_t* codes, const uint8_t* src, int len, uint8_t* dst, int cap) {
    uint32_t pending = 0, freeBits = 8;
    int written = 0;
    for (int x = 0; x < len; x++) {
        uint32_t bits = lengths[src[x]];
        const uint32_t code = codes[src[x]];
        while (freeBits <= bits) {
            bits -= freeBits;
            if (written >= cap) return -1;
            dst[written++] = (uint8_t)((code >> (bits & 0x1F)) | pending);
            pending = 0;
            freeBits = 8;
        }
        if (bits != 0) {
            freeBits -= bits;
            pending |= code << freeBits;
        }
    }
    if (freeBits < 8) {
        if (written >= cap) return -1;
        dst[written++] = (uint8_t)pending;
    }
    return written;
}

// Compress with the stock table.
int huffmanCompress(const uint8_t* src, int len, uint8_t* dst, int cap) {
    return huffmanCompressWith(kEncodeLengths, kEncodeCodes, src, len, dst, cap);
}

// Unpack a 128-byte nibble-packed code-length table (an AF 81 greeting): low nibble + 1 is the
// length of symbol 2i, high nibble + 1 that of symbol 2i+1 (retail
// NET_D2GS_CLIENT_ParseRecvBufferIntoPacketQueues @0x0052a9a5).
void huffmanDecodeNibbles(const uint8_t* packed, uint8_t* lengths) {
    for (int i = 0; i < 128; i++) {
        lengths[2 * i] = (packed[i] & 0x0F) + 1;
        lengths[2 * i + 1] = (packed[i] >> 4) + 1;
    }
}

// Build the canonical per-symbol codes from a 256-entry code-length table, longest code first
// (retail COMPRESS_BuildHuffmanDecodeTable @0x0040adb0).  Returns 0, or -1 for an invalid length.
int huffmanBuildCodes(const uint8_t* lengths, uint8_t* codes) {
    for (int i = 0; i < 256; i++) if (lengths[i] == 0 || lengths[i] > 15) return -1;
    uint8_t sortedSym[256];
    uint8_t sortedLen[256];
    uint16_t offsets[16] = {0};
    for (int i = 0; i < 256; i++) offsets[lengths[i]]++;
    for (int li = 15; li >= 1; li--) { const uint16_t c = offsets[li]; offsets[li] = offsets[0]; offsets[0] += c; }
    for (int sym = 0; sym < 256; sym++) { const int L = lengths[sym]; const int pos = offsets[L]; sortedSym[pos] = (uint8_t)sym; offsets[L] = (uint16_t)(pos + 1); }
    for (int k = 0; k < 256; k++) sortedLen[k] = lengths[sortedSym[k]];
    for (int i = 0; i < 256; i++) codes[i] = 0;
    for (int k = 0; k < 255; k++) {
        const uint32_t prev = codes[sortedSym[k]];
        const int shift = sortedLen[k] - sortedLen[k + 1];
        codes[sortedSym[k + 1]] = (uint8_t)((prev + 1) >> shift);
    }
    return 0;
}

// Prepend the length header to a compressed payload: one byte when the total fits under 0xF0, else
// two bytes `0xF0|(total>>8), total&0xFF`.  Returns the framed length or -1.
int huffmanFrame(const uint8_t* payload, int plen, uint8_t* out, int cap) {
    int total = plen + 1;
    if (total < 0xF0) {
        if (1 + plen > cap) return -1;
        out[0] = (uint8_t)total;
        for (int i = 0; i < plen; i++) out[1 + i] = payload[i];
        return 1 + plen;
    }
    total = plen + 2;
    if (2 + plen > cap) return -1;
    out[0] = (uint8_t)(0xF0 | ((total >> 8) & 0x0F));
    out[1] = (uint8_t)(total & 0xFF);
    for (int i = 0; i < plen; i++) out[2 + i] = payload[i];
    return 2 + plen;
}


// Split the first frame off a server->client D2GS byte stream (retail decode / the receive side of
// NET_D2GS_CLIENT_ParseRecvBufferIntoPacketQueues @0x0052a9a5): the header's total-length field is
// the number of bytes to consume, header included.  Returns that frame size, or 0 when `buf` does
// not yet hold a complete frame (the caller keeps the remainder for the next recv).  The framed
// bytes buf[0..size) are exactly what huffmanDecompress takes.
int huffmanFrameSize(const uint8_t* buf, int len) {
    if (len < 1) return 0;
    if (buf[0] < 0xF0) {
        const int total = buf[0];
        return (total < 1 || len < total) ? 0 : total;
    }
    if (len < 2) return 0;
    const int total = ((buf[0] & 0x0F) << 8) | buf[1];
    return (total < 2 || len < total) ? 0 : total;
}

