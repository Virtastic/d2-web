// The engine reads the top byte of the 32-bit window into a 256-entry dispatch table, so the
// window is unsigned; retail's routine indexes the same 0..255 range.
inline int huffmanHeaderSize(const uint8_t* buf) { return buf[0] < 0xF0 ? 1 : 2; }
inline int huffmanPacketSize(const uint8_t* buf) { return buf[0] < 0xF0 ? buf[0] : (((buf[0] & 0x0F) << 8) + buf[1]); }

// Decompress one framed D2GS packet (header byte(s) carry the compressed length).  Returns the
// number of decoded bytes written to `out` (never more than `outCap`), or -1 on a malformed frame.
int huffmanDecompress(const uint8_t* in, int inLen, uint8_t* out, int outCap) {
    if (inLen < 1) return -1;
    int i = huffmanHeaderSize(in);
    if (inLen < i) return -1;
    int size = huffmanPacketSize(in) - i;
    if (size < 0) return -1;
    int outLen = 0;
    uint32_t window = 0;
    int count = 0x20;
    while (true) {
        if (count >= 8) {
            while (size > 0 && count >= 8) {
                count -= 8;
                size--;
                if (i >= inLen) break;
                window |= (uint32_t)in[i++] << count;
            }
        }
        const uint32_t index = kIndexTable[window >> 0x18];
        const uint32_t bits = kCharacterTable[index];
        const uint32_t slot = (window >> (0x18 - bits)) & kBitMasks[bits];
        const uint32_t consume = kCharacterTable[index + 2 * slot + 2];
        count += (int)consume;
        if (count > 0x20) return outLen;
        const uint32_t symbol = kCharacterTable[index + 2 * slot + 1];
        if (outLen < outCap) out[outLen] = (uint8_t)symbol;
        outLen++;
        window <<= (consume & 0xFF);
    }
}

