// window over the occupancy grid at G +0x3C (cells +0x3C, row offsets +0x40; the first window comes from 0x3D810, then it slides
// one row down per step). At a cell whose centre is set, the eight neighbours form a mask (MSB first: (r-1,c+1), (r,c+1), (r+1,c+1),
