extern "C" void D2Common_3DB20_With(uint32_t room, void (*set)(uint32_t ecx, uint32_t edx))   // 1.13c D2Common+0x3DB20
{
	const uint32_t g = rd(room + 0x20);
	for (int32_t c = 1; c <= int32_t(rd(room + 0x3c)) + 1; ++c) {
		int32_t r = int32_t(rd(room + 0x40)) + 1;
		uint32_t w[9];
		D2Common_3D810_Raw(g + 0x3c, r, c, uint32_t(uintptr_t(w)));
		for (; r >= 1; --r) {
			if (w[4]) {
				uint32_t m = 0;
				const int ord[8] = { 8, 7, 6, 5, 3, 2, 1, 0 };
				for (int k = 0; k < 8; ++k) m = m * 2 + (w[ord[k]] != 0);
				if (m && kWall[m]) {
					const uint32_t idx = rd(rd(g + 0x2c) + uint32_t(r - 1) * 4) + uint32_t(c) - 1;
					set(rd(g + 0x28) + idx * 4, (uint32_t(kWall[m]) << 8) | 0x82);
				}
			}
			if (r > 1) {
				const uint32_t a = rd(g + 0x3c) + (rd(rd(g + 0x40) + uint32_t(r - 2) * 4) + uint32_t(c)) * 4;
				w[0] = w[1]; w[1] = w[2]; w[2] = rd(a - 4);
				w[3] = w[4]; w[4] = w[5]; w[5] = rd(a);
				w[6] = w[7]; w[7] = w[8]; w[8] = rd(a + 4);
			}
		}
	}
}

extern "C" void D2Common_3DB20(uint32_t room) { D2Common_3DB20_With(room, store); }
